#!/usr/bin/env node
/**
 * Pre-compiles the marketplace, the runner and the seeding script to plain JavaScript:  npm run build:node
 *
 * The hosted demo (scripts/gateway.mjs) starts a marketplace process per visitor. Run from TypeScript, every one of
 * them loads the tsx loader and transpiles the whole server at start-up; run from these bundles it does neither,
 * so each visitor costs less memory and a sandbox is ready sooner. `npm run demo` and the tests still run the
 * TypeScript directly.
 *
 * Each bundle is written next to its entry file (server/src/main.bundle.mjs, ...) so the paths the code works out
 * from its own location (repo root, runner parts, the sandbox child) stay the same. npm packages stay external.
 */
import { build } from 'esbuild';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const BUNDLES = [
  ['server/src/main.ts', 'server/src/main.bundle.mjs'],
  ['runner/src/main.ts', 'runner/src/main.bundle.mjs'],
  ['scripts/seed.ts', 'scripts/seed.bundle.mjs'],
  ['server/src/live.ts', 'server/src/live.bundle.mjs'],
];
const t = Date.now();
await Promise.all(BUNDLES.map(([entry, out]) => build({
  entryPoints: [resolve(root, entry)], outfile: resolve(root, out),
  bundle: true, platform: 'node', format: 'esm', target: 'node20', packages: 'external', logLevel: 'warning',
  banner: { js: `// generated by scripts/build-node.mjs from ${entry}; do not edit` },
})));
console.log(`[build:node] ${BUNDLES.length} bundles in ${Date.now() - t} ms`);
